export default function PlantDetails({ plant }: { plant: Plant }) {
  const facts = [
    { icon: <SunIcon />, label: 'Sunlight', value: lightLabel[plant.light] },
    {
      icon: <WaterIcon />,
      label: 'Watering',
      value: `Every ${plant.wateringFrequencyDays} days`,
    },
    {
      icon: <TempIcon />,
      label: 'Temperature',
      value: `${plant.temperatureMin}°C – ${plant.temperatureMax}°C`,
    },
    {
      icon: <HumidityIcon />,
      label: 'Humidity',
      value: humidityLabel[plant.humidity],
    },
    { icon: <SoilIcon />, label: 'Soil', value: plant.soilType },
  ];

  return (
    <section className={css.section}>
      <div className={css.hero}>
        <div className={css.photo}>
          <Image
            src={plant.image || plant.photoUrl}
            alt={plant.commonName}
            fill
            sizes="(min-width: 1440px) 632px, 100vw"
            className={css.photoImage}
            priority
          />
          <span className={css.photoOverlay} />
        </div>

        <div className={css.info}>
          <div className={css.names}>
            <h1 className={css.title}>{plant.commonName}</h1>
            <p className={css.scientific}>{plant.scientificName}</p>
          </div>

          <p className={css.description}>{plant.description}</p>

          <div className={css.actions}>
            <AddToGardenBtn />{' '}
          </div>
        </div>
      </div>

      <div className={css.care}>
        <h2 className={css.careTitle}>Care Requirements</h2>

        <ul className={css.facts}>
          {facts.map(fact => (
            <li key={fact.label} className={css.fact}>
              <span className={css.factIcon}>{fact.icon}</span>
              <span className={css.factLabel}>{fact.label}</span>
              <span className={css.factValue}>{fact.value}</span>
            </li>
          ))}

          <li
            className={`${css.fact} ${plant.toxicToPets ? css.factDanger : ''}`}
          >
            <span className={css.factIcon}>
              {plant.toxicToPets ? <WarningIcon /> : <SafeIcon />}
            </span>
            <span className={css.factLabel}>Pets</span>
            <span className={css.factValue}>
              {plant.toxicToPets ? 'Toxic to pets' : 'Safe for cats and dogs'}
            </span>
          </li>
        </ul>
      </div>
    </section>
  );
}
